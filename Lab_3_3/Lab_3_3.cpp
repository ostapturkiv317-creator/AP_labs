// Математична модель (з графіка):
//      | x + R,             x <= -R        (пряма під кутом 45° через (-R, 0))
//  y = | sqrt(R^2 - x^2),   -R < x <= 0    (верхня дуга кола радіуса R з центром (0, 0))
//      | R - R*x/6,         0 < x <= 6     (пряма через (0, R) та (6, 0))
//      | x - 6,             x > 6          (пряма під кутом 45° через (6, 0))

#include <iostream>
#include <cmath>

using namespace std;

int main()
{
    double x; // вхідний аргумент
    double R; // вхідний параметр (радіус)
    double y; // результат обчислення виразу

    cout << "R = "; cin >> R;
    cout << "x = "; cin >> x;

    // розгалуження в повній формі
    if (x <= -R)
        y = x + R;
    else
        if (x <= 0)
            y = sqrt(R * R - x * x);
        else
            if (x <= 6)
                y = R - R * x / 6;
            else
                y = x - 6;

    cout << endl;
    cout << "y = " << y << endl;

    cin.get();
    return 0;
}

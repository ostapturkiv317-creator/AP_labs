// Область (з рисунка) складається з двох частин:
//  A: верхня ліва чверть круга радіуса R2:
//       x <= 0, y >= 0, x^2 + y^2 <= R2^2
//  B: частина кільця між колами R2 та R1 у нижній правій чверті:
//       x >= 0, y <= 0, R2^2 <= x^2 + y^2 <= R1^2

#include <iostream>

using namespace std;

int main()
{
    double x;  // координата x точки
    double y;  // координата y точки
    double R1; // радіус зовнішнього кола
    double R2; // радіус внутрішнього кола

    cout << "R1 = "; cin >> R1;
    cout << "R2 = "; cin >> R2;
    cout << "x = "; cin >> x;
    cout << "y = "; cin >> y;

    double d = x * x + y * y; // квадрат відстані до початку координат

    if ((x <= 0 && y >= 0 && d <= R2 * R2) ||
        (x >= 0 && y <= 0 && d >= R2 * R2 && d <= R1 * R1))
        cout << "yes" << endl;
    else
        cout << "no" << endl;

    cin.get();
    return 0;
}
